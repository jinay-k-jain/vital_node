export const getTimeline = (patientId: string): TimelineEvent[] => {
  const p = mockPatients.find(pt => pt.id === patientId);
  if (!p) return [];

  const events: TimelineEvent[] = [
    {
      id: `${patientId}-arrival`,
      timestamp: p.arrivalTime,
      type: 'ARRIVAL',
      title: 'Patient arrived',
      description: `Arrival mode: ${p.arrivalMode}. Chief complaint: "${p.chiefComplaint}"`,
    },
    {
      id: `${patientId}-assessment`,
      timestamp: new Date(p.arrivalTime.getTime() + 2 * 60000),
      type: 'ASSESSMENT_CREATED',
      title: 'Initial assessment completed',
      description: 'Vitals recorded, symptoms captured, AI assessment requested.',
    },
    {
      id: `${patientId}-ai`,
      timestamp: p.aiRecommendation?.timestamp || new Date(p.arrivalTime.getTime() + 3 * 60000),
      type: 'AI_ASSESSMENT',
      title: `AI recommendation: ${p.aiRecommendation?.acuity || 'PENDING'}`,
      description: `Confidence: ${p.aiRecommendation?.confidence}%. ${p.aiRecommendation?.safetyFlag || ''}`,
      acuity: p.aiRecommendation?.acuity,
      confidence: p.aiRecommendation?.confidence,
    },
  ];

  if (p.nurseDecision) {
    events.push({
      id: `${patientId}-nurse`,
      timestamp: p.nurseDecision.timestamp,
      type: p.nurseDecision.action,
      title: p.nurseDecision.action === 'OVERRIDE'
        ? `Nurse override → ${p.nurseDecision.finalAcuity}`
        : `Nurse accepted: ${p.nurseDecision.finalAcuity}`,
      description: p.nurseDecision.overrideNote || `Decision by ${p.nurseDecision.nurseName}`,
      acuity: p.nurseDecision.finalAcuity,
    });
  }

  if (p.id === 'p011') {
    events.push({
      id: `${patientId}-deterioration`,
      timestamp: mins(5),
      type: 'VITAL_RECEIVED',
      title: 'New vital reading — condition changed',
      description: 'SpO2 dropped from 97% to 91%. HR increased from 82 to 112. Reassessment triggered.',
    });
    events.push({
      id: `${patientId}-reassess`,
      timestamp: mins(5),
      type: 'AI_ASSESSMENT',
      title: 'AI reassessment: HIGH (upgraded from LOW)',
      description: 'Deterioration detected. Priority queue updated. Nurse notified.',
      acuity: 'HIGH',
      confidence: 85,
    });
  }

  return events.sort((a, b) => a.timestamp.getTime() - b.timestamp.getTime());
};
